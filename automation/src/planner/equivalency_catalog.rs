use serde::Serialize;
use serde_json::Value;
use std::collections::HashSet;

use super::equivalency_output::EquivalencyRulesOutputInput;

const CAMPUS_IDS: &[&str] = &["uw-bothell", "uw-seattle", "uw-tacoma"];
const TRACKED_TAG_ORDER: &[&str] = &[
    "SSC", "AH", "NSC", "QSR", "COMM", "VLPA", "DIV", "NW", "IANDS",
];

#[derive(Clone, Debug, Serialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
struct CatalogCampus<'a> {
    id: &'a str,
    title: &'a str,
    summary: &'a str,
}

#[derive(Clone, Debug, Serialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
struct CatalogEntry {
    id: String,
    target_school_ids: Vec<String>,
    source_course_label: String,
    source_course_title: Option<String>,
    target_outcome: String,
    tags: Vec<String>,
}

pub fn render_transfer_equivalency_catalog_typescript(
    input: &EquivalencyRulesOutputInput,
) -> Result<String, String> {
    let entries = build_catalog_entries(input)?;
    let campuses = [
        CatalogCampus {
            id: "uw-bothell",
            title: "UW Bothell",
            summary: "UW Green River transfer-category rows are sourced from the Equivalency Guide.",
        },
        CatalogCampus {
            id: "uw-seattle",
            title: "UW Seattle",
            summary: "UW Green River transfer-category rows are sourced from the Equivalency Guide.",
        },
        CatalogCampus {
            id: "uw-tacoma",
            title: "UW Tacoma",
            summary: "UW Green River transfer-category rows are sourced from the Equivalency Guide.",
        },
    ];
    let campus_json = serde_json::to_string_pretty(&campuses)
        .map_err(|error| format!("could not serialize transfer-equivalency campuses: {error}"))?;
    let entries_json = serde_json::to_string_pretty(&entries)
        .map_err(|error| format!("could not serialize transfer-equivalency entries: {error}"))?;

    Ok(format!(
        "/* eslint-disable */\n\
         /* auto-generated by automation/equivalency-refresh */\n\
         \n\
         import type {{ TransferEquivalencyTrackedTag }} from \"./transfer-equivalency-tags\";\n\
         import type {{ TransferPlannerCampusId }} from \"./transfer-planner-types\";\n\
         \n\
         export type TransferEquivalencyCatalogCampus = {{\n\
         {campus_type}\n\
         }};\n\
         \n\
         export type TransferEquivalencyCatalogEntry = {{\n\
         {entry_type}\n\
         }};\n\
         \n\
         export const TRANSFER_EQUIVALENCY_CATALOG_CAMPUSES: TransferEquivalencyCatalogCampus[] = {campus_json};\n\
         \n\
         export const TRANSFER_EQUIVALENCY_CATALOG_ENTRIES: TransferEquivalencyCatalogEntry[] = {entries_json};\n",
        campus_type = "  id: TransferPlannerCampusId;\n  title: string;\n  summary?: string;",
        entry_type = "  id: string;\n  targetSchoolIds: TransferPlannerCampusId[];\n  sourceCourseLabel: string;\n  sourceCourseTitle: string | null;\n  targetOutcome: string;\n  tags: TransferEquivalencyTrackedTag[];",
    ))
}

fn build_catalog_entries(input: &EquivalencyRulesOutputInput) -> Result<Vec<CatalogEntry>, String> {
    let mut entries = Vec::new();
    let mut seen_ids = HashSet::new();
    for rule in input
        .official_rules
        .iter()
        .chain(input.derived_rules.iter())
    {
        if rule["isObsoleteSourceCourse"].as_bool() == Some(true) {
            continue;
        }
        let status = rule["ruleStatus"].as_str().unwrap_or_default();
        if !matches!(status, "active" | "legacy") {
            continue;
        }
        let acceptance = rule["acceptanceCategory"].as_str().unwrap_or_default();
        if !matches!(
            acceptance,
            "accepted" | "accepted-with-warning" | "legacy-accepted" | "preferred"
        ) {
            continue;
        }
        let Some(source_course_label) = rule["sourceCourseLabel"].as_str() else {
            continue;
        };
        let source_course_label = source_course_label.trim();
        if source_course_label.is_empty() {
            continue;
        }
        let tags = canonical_tags(&rule["targetRequirementTags"]);
        if tags.is_empty() {
            continue;
        }

        let id = required_string(rule, "id")?;
        if !seen_ids.insert(id.clone()) {
            return Err(format!(
                "duplicate transfer-equivalency catalog rule id {id:?}"
            ));
        }
        let mut target_school_ids = string_array(&rule["targetSchoolIds"]);
        target_school_ids.sort();
        target_school_ids.dedup();
        if target_school_ids.is_empty() {
            return Err(format!(
                "eligible transfer-equivalency rule {id:?} has no targetSchoolIds"
            ));
        }
        if let Some(unknown) = target_school_ids
            .iter()
            .find(|school_id| !CAMPUS_IDS.contains(&school_id.as_str()))
        {
            return Err(format!(
                "eligible transfer-equivalency rule {id:?} has unsupported target campus {unknown:?}"
            ));
        }
        let target_outcome = required_string(rule, "targetOutcome")?;

        entries.push(CatalogEntry {
            id,
            target_school_ids,
            source_course_label: source_course_label.to_string(),
            source_course_title: rule["sourceCourseTitle"].as_str().map(str::to_string),
            target_outcome,
            tags,
        });
    }

    entries.sort_by(|left, right| {
        left.source_course_label
            .to_lowercase()
            .cmp(&right.source_course_label.to_lowercase())
            .then_with(|| left.id.cmp(&right.id))
    });
    Ok(entries)
}

fn required_string(rule: &Value, field: &str) -> Result<String, String> {
    rule[field]
        .as_str()
        .map(str::to_string)
        .filter(|value| !value.trim().is_empty())
        .ok_or_else(|| {
            format!("eligible transfer-equivalency catalog rule is missing string field {field:?}")
        })
}

fn string_array(value: &Value) -> Vec<String> {
    value
        .as_array()
        .into_iter()
        .flatten()
        .filter_map(Value::as_str)
        .map(str::to_string)
        .collect()
}

fn canonical_tags(value: &Value) -> Vec<String> {
    let tags = value
        .as_array()
        .into_iter()
        .flatten()
        .filter_map(Value::as_str)
        .filter_map(canonical_tag)
        .collect::<HashSet<_>>();
    TRACKED_TAG_ORDER
        .iter()
        .filter(|tag| tags.contains(**tag))
        .map(|tag| (*tag).to_string())
        .collect()
}

fn canonical_tag(value: &str) -> Option<&'static str> {
    let normalized: String = value
        .chars()
        .filter(|character| character.is_ascii_alphabetic())
        .flat_map(char::to_uppercase)
        .collect();
    match normalized.as_str() {
        "SSC" | "SOCIALSCIENCES" => Some("SSC"),
        "AH" | "AANDH" | "ARTSHUMANITIES" => Some("AH"),
        "NSC" | "NATURALSCIENCES" => Some("NSC"),
        "QSR" => Some("QSR"),
        "COMM" | "BASICSKILLSCOMMUNICATION" => Some("COMM"),
        "VLPA" => Some("VLPA"),
        "DIV" => Some("DIV"),
        "NW" => Some("NW"),
        "IANDS" | "IS" | "INDIVIDUALSANDSOCIETIES" => Some("IANDS"),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn projects_only_current_nonobsolete_accepted_category_rows() {
        let input = EquivalencyRulesOutputInput {
            official_rules: vec![
                json!({
                    "id": "guide:sequence",
                    "ruleStatus": "active",
                    "acceptanceCategory": "accepted-with-warning",
                    "isObsoleteSourceCourse": false,
                    "targetSchoolIds": ["uw-seattle"],
                    "sourceCourseLabel": "CHEM& 261 + CHEM& 262 + CHEM& 263",
                    "sourceCourseTitle": null,
                    "targetOutcome": "Full-sequence outcome only.",
                    "targetRequirementTags": ["NSc", "A&H"]
                }),
                json!({
                    "id": "guide:obsolete",
                    "ruleStatus": "active",
                    "acceptanceCategory": "accepted",
                    "isObsoleteSourceCourse": true,
                    "targetSchoolIds": ["uw-seattle"],
                    "sourceCourseLabel": "OLD 100",
                    "targetOutcome": "Obsolete",
                    "targetRequirementTags": ["SSc"]
                }),
                json!({
                    "id": "guide:no-credit",
                    "ruleStatus": "active",
                    "acceptanceCategory": "not-transferable",
                    "isObsoleteSourceCourse": false,
                    "targetSchoolIds": ["uw-seattle"],
                    "sourceCourseLabel": "NOCR 100",
                    "targetOutcome": "No credit",
                    "targetRequirementTags": ["SSc"]
                }),
                json!({
                    "id": "guide:untracked-tag",
                    "ruleStatus": "active",
                    "acceptanceCategory": "accepted",
                    "isObsoleteSourceCourse": false,
                    "targetSchoolIds": ["uw-seattle"],
                    "sourceCourseLabel": "OTHER 100",
                    "targetOutcome": "Untracked category",
                    "targetRequirementTags": ["unmapped"]
                }),
            ],
            derived_rules: vec![json!({
                "id": "derived:legacy-sequence",
                "ruleStatus": "legacy",
                "acceptanceCategory": "legacy-accepted",
                "isObsoleteSourceCourse": false,
                "targetSchoolIds": ["uw-seattle"],
                "sourceCourseLabel": "MATH& 151 + MATH& 152 + MATH& 153 + MATH& 264",
                "targetOutcome": "Retained older full path.",
                "targetRequirementTags": ["NSc"]
            })],
        };

        let entries = build_catalog_entries(&input).unwrap();
        assert_eq!(entries.len(), 2);
        assert_eq!(
            entries[0].source_course_label,
            "CHEM& 261 + CHEM& 262 + CHEM& 263"
        );
        assert_eq!(entries[0].target_outcome, "Full-sequence outcome only.");
        assert_eq!(entries[0].tags, vec!["AH", "NSC"]);
        assert_eq!(
            entries[1].source_course_label,
            "MATH& 151 + MATH& 152 + MATH& 153 + MATH& 264"
        );
        assert_eq!(entries[1].tags, vec!["NSC"]);
    }

    #[test]
    fn generated_typescript_keeps_the_category_catalog_contract() {
        let input = EquivalencyRulesOutputInput {
            official_rules: vec![json!({
                "id": "guide:1",
                "ruleStatus": "active",
                "acceptanceCategory": "accepted",
                "isObsoleteSourceCourse": false,
                "targetSchoolIds": ["uw-seattle"],
                "sourceCourseLabel": "ACCT& 201 + ACCT& 202",
                "sourceCourseTitle": "Principles of Accounting",
                "targetOutcome": "Full two-course sequence.",
                "targetRequirementTags": ["SSc"]
            })],
            derived_rules: Vec::new(),
        };

        let output = render_transfer_equivalency_catalog_typescript(&input).unwrap();
        assert!(output.contains("TransferEquivalencyCatalogEntry[]"));
        assert!(output.contains("\"sourceCourseLabel\": \"ACCT& 201 + ACCT& 202\""));
        assert!(output.contains("\"targetOutcome\": \"Full two-course sequence.\""));
        assert!(output.contains("\"tags\": [\n      \"SSC\""));
        assert!(output.ends_with('\n'));
    }
}
